/**
 * The team's own handbook for this console, in Arabic.
 *
 * Content rather than code, kept here rather than in a migration for the reason
 * `normalise_kb_formatting` gives for the same choice: the seeding job needs
 * `normaliseArticleHtml` and `sanitiseArticleHtml`, and a hand-written SQL twin
 * of either would be a second implementation to keep in step with the first.
 * `worker/handlers/seed-console-handbook.ts` is what puts it in the database.
 *
 * Four decisions are worth knowing before editing this file.
 *
 * **Arabic, with the controls left in English.** Arabic is the default locale
 * and the language the team works in, but a button says `Resolve after sending`
 * on screen and translating it in the prose would send somebody hunting for a
 * control that does not exist. So every name of a thing you click keeps the
 * spelling it has in the interface, inside `code`, which `.kb-article` renders
 * as a chip — visibly a literal rather than a word in the sentence.
 *
 * **Every folder carries a role floor, and the articles inherit it.** The floor
 * is on the folder rather than repeated on each article so that a seventeenth
 * article added later cannot arrive at the wrong audience by omission; see
 * `lib/kb/internal.ts` for what a floor is and where it is applied. The
 * articles are `agents_only` on their own row as well, which is belt and
 * braces: production's imported internal articles are marked `public` and are
 * internal only through their folder, and one query that forgot the folder
 * would publish them — the unnumbered §6 trap in `docs/PROJECT-STATE.md`, "A
 * `published`/`public` article can sit inside a folder nobody may read".
 * Nothing here relies on that being remembered.
 *
 * **The slugs are ASCII and prefixed `handbook-`.** Arabic slugs are the rule
 * for this knowledge base — `lib/kb/slug.ts` exists because ASCII slugify
 * erases Arabic entirely — and that rule is about not destroying a title a
 * reader will see in a URL. These are different: no customer-facing URL ever
 * resolves to an internal article, the slug here is a stable key the seeding
 * job re-finds the row by, and a title reworded in review must not move it.
 *
 * **The bodies are already normalised.** `handbook.test.ts` asserts each one is
 * a fixed point of `normaliseArticleHtml(sanitiseArticleHtml(html))`, so what
 * the job stores is byte-for-byte what is written here and a second run has
 * nothing to change. If that test fails after an edit, the body picked up
 * something the formatting standard removes — a `div`, an `h1`, a stray class —
 * rather than the test being wrong.
 */

export type HandbookArticle = {
  /** Stable identity. Becomes `kb_articles.external_id` as `handbook:<key>`. */
  key: string;
  slug: string;
  title: string;
  bodyHtml: string;
};

export type HandbookFolder = {
  key: string;
  slug: string;
  name: string;
  description: string;
  /** The most junior role that may read anything in here. */
  minRole: AgentRole;
  articles: HandbookArticle[];
};

